/*
 * SSD1306 driver for the 0.42" 72x40 OLED found on ESP32-C3 SuperMini
 * OLED boards. I2C: SDA=GPIO5, SCL=GPIO6, address 0x3C.
 *
 * The 72x40 panel is wired to the middle of the SSD1306's 128x64 RAM,
 * so every column write must be shifted by 28 pixels.
 */

#include <string.h>

#include "display.h"
#include "driver/i2c_master.h"
#include "esp_log.h"
#include "freertos/FreeRTOS.h"
#include "freertos/semphr.h"

#define I2C_SDA_GPIO      5
#define I2C_SCL_GPIO      6
#define I2C_FREQ_HZ       400000
#define OLED_I2C_ADDR     0x3C
#define OLED_COL_OFFSET   28
#define I2C_TIMEOUT_MS    1000

/* SSD1306 control bytes */
#define CTRL_CMD          0x00
#define CTRL_DATA         0x40

static const char *TAG = "display";

static i2c_master_dev_handle_t s_dev;
static uint8_t s_framebuffer[DISPLAY_PAGES][DISPLAY_WIDTH];
static SemaphoreHandle_t s_mutex;

